#include <iostream>
using namespace std;
int main()
{
    int A, B;

    cin >> A >> B;
   // C = A + B;
    cout << (A + B) << endl;

    // C = A - B;
    cout << (A - B) << endl;

    // C = A * B;
    cout << (A * B) << endl;

    // C = A / B;
    cout << (A / B) << endl;

    // C = A % B;
    cout << (A % B)  << endl;

    return 0;
}